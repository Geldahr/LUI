"""Measure per-character advances from the /lui fontcal screenshots and
generate src/Utils/font_widths.lua.

Usage: python tools/fonts/measure_fonts.py <screenshot_dir>
  <screenshot_dir> holds exactly the calibration screenshots (one per page,
  in time order), taken at game UI scale 100% with the page area shown in
  the window footer (PAGE_W x PAGE_H below). Requires Pillow.


Rebuilds the exact layout of src/UI/font_calibration.lua for the page area
(PAGE_W x PAGE_H), maps screenshot i (time order) to page i, and for each
cell measures the ink extent of "|" + char*reps + "|".
advance(char) = (ink(cell) - ink("||" reference)) / reps
"""
import glob, math, os, sys
from PIL import Image

SHOTS = sorted(glob.glob(os.path.join(sys.argv[1], "ScreenShot_*.jpg")))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src", "Utils", "font_widths.lua")
PAGE_W, PAGE_H = 1880, 1000
ORIGIN_X, ORIGIN_Y = 30, 30  # window (20,20) + MARGIN 10
HEADER, GAP = 16, 3
FONTS = [("Verdana", [10, 12, 14, 16, 18, 20, 22, 23]), ("VerdanaBold", [16]), ("Arial", [12]),
         ("BookAntiqua", [12, 14, 16, 18, 20, 22, 24, 26, 28, 32, 36]),
         ("BookAntiquaBold", [12, 14, 18, 19, 22, 24]),
         ("TrajanPro", [13, 14, 15, 16, 18, 19, 20, 21, 23, 24, 25, 26, 28]),
         ("TrajanProBold", [16, 22, 24, 25, 30, 36]), ("FixedSys", [15]), ("LucidaConsole", [12])]
EXTRA = list("àáâäçèéêëìíîïñòóôöùúûüýÀÁÂÄÇÈÉÊËÍÎÓÔÖÚÛÜßæœ€£§°²µ¤¨")
CHARS = [""] + [chr(c) for c in range(32, 127)] + EXTRA


def reps(size):
    return 8 if size <= 14 else (5 if size <= 22 else 4)


def cell_size(family, size):
    factor = 1.4 if family.startswith("Trajan") else 1.15
    return math.floor((reps(size) + 2) * factor * size) + 10, size + 6


def layout():
    pages = [[]]
    y = 0
    for family, sizes in FONTS:
        for size in sizes:
            cw, ch = cell_size(family, size)
            cols = max(1, PAGE_W // (cw + GAP))
            if y + HEADER + ch + GAP > PAGE_H:
                pages.append([]); y = 0
            y += HEADER
            col = 0
            for c in CHARS:
                if col == 0 and y + ch + GAP > PAGE_H:
                    pages.append([]); y = 0
                pages[-1].append((col * (cw + GAP), y, cw, ch, family, size, c))
                col += 1
                if col >= cols:
                    col = 0; y += ch + GAP
            if col != 0:
                y += ch + GAP
    return pages


def ink_extent(img, x, y, w, h):
    """first/last column with bright (white text) pixels inside the label area"""
    px = img.load()
    first = last = None
    clipped = False
    for cx in range(x + 4, x + w - 4):
        for cy in range(y + 1, y + h - 1):
            r, g, b = px[cx, cy]
            if r > 110 and g > 110:
                if first is None:
                    first = cx
                last = cx
                break
    if last is not None and last >= x + w - 5:
        clipped = True
    return first, last, clipped


def lua_string(c):
    return '"' + c.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(result):
    lines = [
        "-- This Source Code Form is subject to the terms of the Mozilla Public",
        "-- License, v. 2.0. If a copy of the MPL was not distributed with this",
        "-- file, You can obtain one at https://mozilla.org/MPL/2.0/.",
        "--",
        "-- GENERATED by tools/fonts/measure_fonts.py -- DO NOT EDIT",
        "-- Source: in-game calibration screenshots (/lui fontcal), pixel advance",
        "-- of every character per LotRO font and size.",
        "local Utils = _G.LUI.Utils",
        "",
        "local CHARS = {",
    ]
    chars = CHARS[1:]
    for i in range(0, len(chars), 16):
        lines.append("    " + ", ".join(lua_string(c) for c in chars[i:i + 16]) + ",")
    lines += ["}", "", "local ADVANCES = {"]
    for family, sizes in FONTS:
        for size in sizes:
            key = "%s%d" % (family, size)
            adv = result[key]["advance"]
            lines.append("    %s = { %s }," % (key, ", ".join(str(int(round(adv[c]))) for c in chars)))
    lines += ["}", "", "-- rendered sizes per family, ascending (same lists as FONT_TO_LOTRO)",
              "Utils.FONT_SIZES = {"]
    for family, sizes in FONTS:
        lines.append("    %s = { %s }," % (family, ", ".join(str(s) for s in sizes)))
    lines += [
        "}",
        "",
        "-- FONT_CHAR_WIDTHS[\"Verdana12\"][\"m\"] = advance in pixels",
        "local widths = {}",
        "for key, values in pairs(ADVANCES) do",
        "    local map = {}",
        "    for i = 1, #CHARS do",
        "        map[CHARS[i]] = values[i]",
        "    end",
        "    widths[key] = map",
        "end",
        "Utils.FONT_CHAR_WIDTHS = widths",
        "",
    ]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main():
    pages = layout()
    if len(pages) != len(SHOTS):
        raise SystemExit("pages %d != screenshots %d" % (len(pages), len(SHOTS)))
    raw = {}
    problems = []
    for page_index, (cells, shot) in enumerate(zip(pages, SHOTS), 1):
        img = Image.open(shot).convert("RGB")
        for (x, y, w, h, family, size, c) in cells:
            first, last, clipped = ink_extent(img, ORIGIN_X + x, ORIGIN_Y + y, w, h)
            key = "%s%d" % (family, size)
            if first is None:
                problems.append((key, c, "no ink"))
                continue
            if clipped:
                problems.append((key, c, "clipped"))
            raw.setdefault(key, {})[c] = last - first + 1
    result = {}
    for family, sizes in FONTS:
        for size in sizes:
            key = "%s%d" % (family, size)
            cells = raw.get(key, {})
            ref = cells.get("")
            if ref is None:
                problems.append((key, "", "no reference")); continue
            n = reps(size)
            widths = {}
            for c in CHARS[1:]:
                if c in cells:
                    widths[c] = (cells[c] - ref) / n
            result[key] = {"ref": ref, "reps": n, "advance": widths}
    if problems:
        for p in problems:
            print("  ", p)
        raise SystemExit("measurement problems: %d" % len(problems))
    write_lua(result)
    print("fonts measured:", len(result), "->", os.path.relpath(OUT, REPO))
    # non-integer advances hint at measurement noise or kerning
    odd = []
    for key, data in result.items():
        for c, a in data["advance"].items():
            if abs(a - round(a)) > 0.15:
                odd.append((key, c, a))
    print("non-integer advances:", len(odd))
    for o in odd[:20]:
        print("  ", o)


main()
