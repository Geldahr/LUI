# Packs the wiki bestiary (src/Encyclopedia/data.lua, dumped to JSON by
# bestiary_dump.lua) into blobs. The decode layer reproduces the raw
# data.lua entry shape exactly; lookup/group indexes replicate the
# semantics of src/Encyclopedia/data_access.lua and are baked at build time.

B_SCALARS = ["n", "bn", "tl", "v", "g", "s", "sp", "r", "a", "i", "t"]
B_CE = ["f", "fm", "sm", "rt"]
B_RS = ["cr", "so", "ta", "ph"]
B_MI = ["co", "ad", "fi", "be", "li", "we", "sh", "fr", "lt"]
B_LISTS = ["ab", "qi", "di", "w", "cw"]

_LUA_SPACE = " \t\n\r\f\v"


def _lua_trim(s):
    return s.strip(_LUA_SPACE)


def _lua_lower(s):
    # Lua 5.1 string.lower is ASCII-only; replicate exactly
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in s)


def _lua_normalize_name(name):
    name = _lua_trim(name)
    if name == "":
        return None
    if _lua_lower(name)[:4] == "the ":
        name = _lua_trim(name[4:])
    import re as _re
    name = _re.sub(r"[ \t\n\r\f\v]*\.+$", "", name)
    name = _lua_trim(name)
    if name == "":
        return None
    return name


def _lua_normalized_lower(name):
    normalized = _lua_normalize_name(name)
    if normalized is not None:
        return _lua_lower(normalized)
    return _lua_lower(_lua_trim(name))


# localized target-name bridge: join wiki base names to mobs.xml, emit
# per-language {normalized localized name -> English base name} maps. 96%
# of wiki names match exactly; wiki disambiguation suffixes are stripped
# as a fallback. Identity translations are skipped (the English index
# already resolves them), and everything else falls back to English.
# D.display is the inverse ({English base name -> localized}) for the
# render-time name swap; keys/cache/index stay English underneath.
def _emit_bestiary_name_bridge(data_dir, out_dir, entries):
    mob_ids_by_name = {}
    for m in re.finditer(r'<mob id="(\d+)" name="([^"]*)"',
                         open(os.path.join(data_dir, "mobs.xml"), encoding="utf-8").read()):
        mob_ids_by_name.setdefault(m.group(2), []).append(int(m.group(1)))

    base_names = {}
    for key, entry in entries.items():
        if "alias" not in entry:
            base_names[entry.get("bn") or key] = True

    def match_ids(bn):
        ids = mob_ids_by_name.get(bn)
        if ids is None:
            ids = mob_ids_by_name.get(re.sub(r"\s*\([^)]*\)$", "", bn))
        return ids

    for lang in ("fr", "de"):
        labels = parse_labels(data_dir, lang, "mobs")
        mapping = {}
        display = {}
        matched, collisions = 0, 0
        for bn in base_names:
            ids = match_ids(bn)
            if not ids:
                continue
            for mob_id in ids:
                localized = labels.get(mob_id)
                if localized:
                    matched += 1
                    if localized != bn:
                        display[bn] = localized
                    lookup = _lua_normalized_lower(localized)
                    if lookup != _lua_normalized_lower(bn):
                        if lookup in mapping and mapping[lookup] != bn:
                            collisions += 1
                        else:
                            mapping[lookup] = bn
                    break
        parts = ["D.map = {\n"]
        for lookup in sorted(mapping):
            parts.append("[%s] = %s,\n" % (lua_string(lookup), lua_string(mapping[lookup])))
        parts.append("}\n")
        parts.append("D.display = {\n")
        for bn in sorted(display):
            parts.append("[%s] = %s,\n" % (lua_string(bn), lua_string(display[bn])))
        parts.append("}\n")
        write_file(out_dir, "names_%s.lua" % lang, parts)
        print("bestiary name bridge %s: %d matched, %d bridged, %d display, %d collisions dropped"
              % (lang, matched, len(mapping), len(display), collisions))


# localized string pools: pool_fr/pool_de mirror pool.lua entry-for-entry
# (same indices), with strings replaced where a game-data label joins to the
# English text. Name fields (n/bn/tl) always stay English: the resolution
# index, group keys and the observation cache are keyed by them. Ratings
# (ce/rs/mi) have no label source in the dump and stay English this phase.
_B_POOL_GROUP_OF_SCALAR = {
    "g": "genus", "s": "species", "sp": "subspecies",
    "r": "location", "a": "location", "v": "location", "i": "location",
    "t": "tier",
}
_B_POOL_GROUPS = ("genus", "species", "subspecies", "tier", "location",
                  "ability", "quest", "deed", "item", "rating")
_B_QI_PREFIX_RE = re.compile(r"^(-?\s*\[[^\]]*\]\s*)(.*)$")
_B_SUFFIX_RE = re.compile(r"^(.*?)(\s*\([^)]*\))$")


def _emit_bestiary_localized_pools(data_dir, out_dir, entries, record_keys,
                                   pool, pool_ref):
    protected = set()
    group_indices = {g: set() for g in _B_POOL_GROUPS}
    for key in record_keys:
        entry = entries[key]
        for f in ("n", "bn", "tl"):
            if f in entry:
                protected.add(pool_ref[entry[f]])
        for f, group in _B_POOL_GROUP_OF_SCALAR.items():
            if f in entry:
                group_indices[group].add(pool_ref[entry[f]])
        for m in ("ce", "rs", "mi"):
            for v in entry.get(m, {}).values():
                group_indices["rating"].add(pool_ref[v])
        for f, group in (("ab", "ability"), ("qi", "quest"), ("di", "deed"),
                         ("w", "item"), ("cw", "item")):
            for v in entry.get(f, []):
                group_indices[group].add(pool_ref[v])

    def key_joined(lang, db):
        # label-key join (enum labels): EN value -> localized value;
        # identity hits kept so coverage reflects "a label exists"
        en = parse_labels(data_dir, "en", db, raw_keys=True)
        loc = parse_labels(data_dir, lang, db, raw_keys=True)
        out = {}
        for k, en_v in en.items():
            lv = loc.get(k)
            if lv:
                out.setdefault(en_v, lv)
        return out

    def id_joined(lang, db):
        # same-id join: EN name -> localized name, majority on conflicts
        en = parse_labels(data_dir, "en", db, raw_keys=True)
        loc = parse_labels(data_dir, lang, db, raw_keys=True)
        votes = {}
        for k, en_v in en.items():
            lv = loc.get(k)
            if lv:
                votes.setdefault(en_v, {})
                votes[en_v][lv] = votes[en_v].get(lv, 0) + 1
        return {en_v: max(sorted(c), key=c.get) for en_v, c in votes.items()}

    def merged(*dicts):
        out = {}
        for d in dicts:
            for k, v in d.items():
                out.setdefault(k, v)
        return out

    sizes = {}
    for lang in ("fr", "de"):
        quest_dict = id_joined(lang, "quests")
        dicts = {
            "genus": key_joined(lang, "enum-Genus"),
            "species": key_joined(lang, "enum-Species"),
            "subspecies": key_joined(lang, "enum-SubSpecies"),
            "tier": key_joined(lang, "enum-MobType"),
            # wiki location strings mix areas, dungeons, instances,
            # landmarks and quest-instance names
            "location": merged(id_joined(lang, "geoAreas"),
                               id_joined(lang, "dungeons"),
                               id_joined(lang, "instances"),
                               id_joined(lang, "landmarks"),
                               quest_dict),
            "ability": merged(id_joined(lang, "effects"),
                              id_joined(lang, "skills")),
            "quest": quest_dict,
            "deed": id_joined(lang, "deeds"),
            "item": id_joined(lang, "items"),
            "rating": {},
        }

        def base_translate(group, s):
            d = dicts[group]
            hit = d.get(s)
            if hit:
                return hit
            if group in ("quest", "location"):
                # qi strings are "[level] Name" (some "- [level] Name")
                m = _B_QI_PREFIX_RE.match(s)
                if m:
                    hit = d.get(m.group(2))
                    if hit:
                        return m.group(1) + hit
            # wiki disambiguation suffixes: translate base, keep suffix
            m = _B_SUFFIX_RE.match(s)
            if m:
                hit = d.get(m.group(1))
                if hit:
                    return hit + m.group(2)
            return None

        def translate(group, s):
            hit = base_translate(group, s)
            if hit:
                return hit
            if " / " in s:
                parts = [base_translate(group, p) for p in s.split(" / ")]
                if all(parts):
                    return " / ".join(parts)
            return None

        localized = list(pool)
        changed = 0
        report = []
        for group in _B_POOL_GROUPS:
            indices = group_indices[group] - protected
            hits = 0
            for idx in sorted(indices):
                translation = translate(group, pool[idx - 1])
                if translation is None:
                    continue
                hits += 1
                if translation != pool[idx - 1] and localized[idx - 1] == pool[idx - 1]:
                    localized[idx - 1] = translation
                    changed += 1
            if indices:
                report.append("%s %d/%d" % (group, hits, len(indices)))

        pool_blob = "".join(localized)
        poffs, pos = [], 1
        for v in localized:
            poffs.append(pos)
            pos += byte_len(v)
        poffs.append(pos)
        poff_w = width_for(pos)
        poff_blob = "".join(b93(x, poff_w) for x in poffs)
        name = "pool_%s.lua" % lang
        sizes[name] = write_file(out_dir, name, [
            "D.poff_width = %d\n" % poff_w,
            emit_blob("POOL", pool_blob),
            emit_blob("POFF", poff_blob),
        ])
        print("bestiary pool %s: %d/%d strings localized (%d name-protected)"
              % (lang, changed, len(pool), len(protected)))
        print("  coverage: " + ", ".join(report))
    return sizes


def convert_bestiary(json_path, out_dir, data_dir=None):
    import json as _json
    t0 = time.time()
    with open(json_path, encoding="utf-8") as f:
        entries = _json.load(f)["entries"]
    keys = sorted(entries)
    print("bestiary source: %d entries" % len(keys))

    aliases = {}
    record_keys = []
    for key in keys:
        entry = entries[key]
        if "alias" in entry:
            target = _lua_trim(entry["alias"])
            for lookup in (_lua_lower(key), _lua_normalized_lower(key)):
                aliases.setdefault(lookup, target)
        else:
            record_keys.append(key)
    count = len(record_keys)

    # one shared string pool for every string value
    pool_set = set()
    for key in record_keys:
        entry = entries[key]
        for f in B_SCALARS:
            if f in entry:
                pool_set.add(entry[f])
        for m, subs in (("ce", B_CE), ("rs", B_RS), ("mi", B_MI)):
            for sub in entry.get(m, {}).values():
                pool_set.add(sub)
        for f in B_LISTS:
            for v in entry.get(f, []):
                pool_set.add(v)
    pool = sorted(pool_set)
    pool_ref = {v: i + 1 for i, v in enumerate(pool)}
    ref_w = width_for(len(pool))

    l_w = width_for(max((e["l"][1] for e in entries.values() if "l" in e), default=0) + 1)
    m_w = width_for(max((e["m"][1] for e in entries.values() if "m" in e), default=0) + 1)
    p_w = width_for(max((e["p"][1] for e in entries.values() if "p" in e), default=0) + 1)

    def encode_entry(entry):
        parts = []
        for f in B_SCALARS:
            parts.append(b93(pool_ref[entry[f]] if f in entry else 0, ref_w))
        for f, w in (("l", l_w), ("m", m_w), ("p", p_w)):
            if f in entry:
                parts.append(b93(entry[f][0] + 1, w))
                parts.append(b93(entry[f][1] + 1, w))
            else:
                parts.append(b93(0, w))
                parts.append(b93(0, w))
        for m, subs in (("ce", B_CE), ("rs", B_RS), ("mi", B_MI)):
            mv = entry.get(m, {})
            for sub in subs:
                parts.append(b93(pool_ref[mv[sub]] if sub in mv else 0, ref_w))
        for f in B_LISTS:
            values = entry.get(f, [])
            parts.append(b93(len(values), 1))
            for v in values:
                parts.append(b93(pool_ref[v], ref_w))
        return "".join(parts)

    encoded = [encode_entry(entries[k]) for k in record_keys]
    data_blob = "".join(encoded)
    offs, pos = [], 1
    for e in encoded:
        offs.append(pos)
        pos += len(e)
    offs.append(pos)
    off_w = width_for(pos)
    off_blob = "".join(b93(x, off_w) for x in offs)

    keys_blob = "".join(record_keys)
    koffs, pos = [], 1
    for k in record_keys:
        koffs.append(pos)
        pos += byte_len(k)
    koffs.append(pos)
    koff_w = width_for(pos)
    koff_blob = "".join(b93(x, koff_w) for x in koffs)

    pool_blob = "".join(pool)
    poffs, pos = [], 1
    for v in pool:
        poffs.append(pos)
        pos += byte_len(v)
    poffs.append(pos)
    poff_w = width_for(pos)
    poff_blob = "".join(b93(x, poff_w) for x in poffs)

    ord_w = width_for(count)

    # lookup index: raw_lower and normalized_lower of every key -> ordinal;
    # deterministic first-in-sorted-key-order wins on collisions
    lookup_map = {}
    for n, key in enumerate(record_keys):
        for lookup in (_lua_lower(key), _lua_normalized_lower(key)):
            if lookup != "" and lookup not in lookup_map:
                lookup_map[lookup] = n + 1
    lookup_parts, loffs, pos = [], [], 1
    for lookup in sorted(lookup_map):
        part = "\n%s\t%s" % (lookup, b93(lookup_map[lookup], ord_w))
        loffs.append(pos)
        lookup_parts.append(part)
        pos += byte_len(part)
    lookup_blob = "".join(lookup_parts) + "\n"
    loff_w = width_for(pos)
    loff_blob = "".join(b93(x, loff_w) for x in loffs)

    # group index: normalized-lower base name -> ordinals (sorted-key order)
    groups = {}
    for n, key in enumerate(record_keys):
        entry = entries[key]
        base = entry.get("bn") or entry.get("n") or key
        base_lower = _lua_normalized_lower(base)
        groups.setdefault(base_lower, []).append(n + 1)
    group_parts, goffs, pos = [], [], 1
    for base in sorted(groups):
        part = "\n%s\t%s" % (base, "".join(b93(o, ord_w) for o in groups[base]))
        goffs.append(pos)
        group_parts.append(part)
        pos += byte_len(part)
    groups_blob = "".join(group_parts) + "\n"
    goff_w = width_for(pos)
    goff_blob = "".join(b93(x, goff_w) for x in goffs)

    # python round-trip: decode every record and compare to the source
    def decode_entry(n):
        pos = offs[n] - 1
        out = {}

        def take(w):
            nonlocal pos
            v = u93(data_blob, pos, w)
            pos += w
            return v

        for f in B_SCALARS:
            ref = take(ref_w)
            if ref:
                out[f] = pool[ref - 1]
        for f, w in (("l", l_w), ("m", m_w), ("p", p_w)):
            lo, hi = take(w), take(w)
            if lo or hi:
                out[f] = [lo - 1, hi - 1]
        for m, subs in (("ce", B_CE), ("rs", B_RS), ("mi", B_MI)):
            mv = {}
            for sub in subs:
                ref = take(ref_w)
                if ref:
                    mv[sub] = pool[ref - 1]
            if mv:
                out[m] = mv
        for f in B_LISTS:
            n_items = take(1)
            if n_items:
                out[f] = [pool[take(ref_w) - 1] for _ in range(n_items)]
        return out

    for n, key in enumerate(record_keys):
        if decode_entry(n) != entries[key]:
            raise AssertionError("bestiary round-trip mismatch: " + key)
    print("round-trip: all %d records verified (+%d aliases)" % (count, len(aliases)))
    os.makedirs(out_dir, exist_ok=True)
    sizes = {}
    if data_dir:
        _emit_bestiary_name_bridge(data_dir, out_dir, entries)
        sizes.update(_emit_bestiary_localized_pools(
            data_dir, out_dir, entries, record_keys, pool, pool_ref))
    sizes["records.lua"] = write_file(out_dir, "records.lua", [
        emit_blob("DATA", data_blob),
        emit_blob("OFF", off_blob),
        emit_blob("KEYS", keys_blob),
        emit_blob("KOFF", koff_blob),
    ])
    sizes["pool.lua"] = write_file(out_dir, "pool.lua", [
        "D.poff_width = %d\n" % poff_w,
        emit_blob("POOL", pool_blob),
        emit_blob("POFF", poff_blob),
    ])
    sizes["index.lua"] = write_file(out_dir, "index.lua", [
        "D.lookup_count = %d\n" % len(lookup_map),
        "D.group_count = %d\n" % len(groups),
        emit_blob("LOOKUP", lookup_blob),
        emit_blob("LOFF", loff_blob),
        emit_blob("GROUPS", groups_blob),
        emit_blob("GOFF", goff_blob),
    ])
    alias_lines = ["D.aliases = {\n"]
    for lookup in sorted(aliases):
        alias_lines.append("[%s] = %s,\n" % (lua_string(lookup), lua_string(aliases[lookup])))
    alias_lines.append("}\n")
    sizes["manifest.lua"] = write_file(out_dir, "manifest.lua", [
        "D.count = %d\n" % count,
        "D.ref_width = %d\n" % ref_w,
        "D.ord_width = %d\n" % ord_w,
        "D.off_width = %d\n" % off_w,
        "D.koff_width = %d\n" % koff_w,
        "D.loff_width = %d\n" % loff_w,
        "D.goff_width = %d\n" % goff_w,
        "D.l_width = %d\n" % l_w,
        "D.m_width = %d\n" % m_w,
        "D.p_width = %d\n" % p_w,
    ] + alias_lines)

    total = 0
    print("emitted files:")
    for name in sorted(sizes):
        total += sizes[name]
        print("  %-14s %8.2f MB" % (name, sizes[name] / 1e6))
    print("  %-14s %8.2f MB" % ("TOTAL", total / 1e6))
    print("done in %.1fs\n" % (time.time() - t0))


# ---------------------------------------------------------------- nodes ----
# Harvest/resource nodes: world objects the player collects from (deposits,
# branches, crop fields, artifacts). Each node is a profession-gated item in
# items.xml (requiredProfession="<prof_item_id>;<tier>") that also appears in
# containers.xml; its yields resolve through loots.xml trophy lists (repeated
# independent rolls: dropFrequency x quantity) and treasure lists (each entry
# is one guaranteed weighted pick from an <itemsTable>).
#
# Output is one small plain-Lua file (a few hundred nodes): localized node
# name -> item id lookup, per-node yields with quantity ranges and a band
# (1 = guaranteed, 2 = bonus, 3 = rare), localized profession/tier names and
# the per-profession-tier badge icon layers.

NODE_RARE_FREQ = 0.02


def convert_nodes(data_dir, out_dir, langs):
    t0 = time.time()

    # profession-gated items: id -> (profession item id, tier)
    req = {}
    for _, el in ET.iterparse(os.path.join(data_dir, "items.xml")):
        if el.tag == "item":
            rp = el.get("requiredProfession")
            if rp:
                parts = rp.split(";")
                tier = int(parts[1]) if len(parts) > 1 else 0
                req[int(el.get("key"))] = (int(parts[0]), tier)
            el.clear()

    # profession id -> key ("PROSPECTOR"), plus tier badge icon layers
    prof_key, prof_defs, icons = {}, [], {}
    cur_prof = None
    for ev, el in ET.iterparse(os.path.join(data_dir, "crafting.xml"), events=("start", "end")):
        # vocation blocks cross-reference professions as bare
        # <profession identifier="..."/>; only keyed elements define one
        if ev == "start" and el.tag == "profession" and el.get("key"):
            cur_prof = el.get("key")
            prof_key[int(el.get("identifier"))] = cur_prof
            prof_defs.append((int(el.get("identifier")), cur_prof, el.get("name")))
            icons[cur_prof] = {}
        elif ev == "end" and el.tag == "professionTier":
            if el.get("icon"):
                icons[cur_prof][int(el.get("identifier"))] = el.get("icon")
            el.clear()

    # loots.xml: trophy lists, treasure lists, weighted items tables
    trophy, treasure, tables = {}, {}, {}
    cur_list = None
    for ev, el in ET.iterparse(os.path.join(data_dir, "loots.xml"), events=("start", "end")):
        if ev == "start":
            if el.tag in ("trophyList", "treasureList", "itemsTable"):
                cur_list = []
                {"trophyList": trophy, "treasureList": treasure,
                 "itemsTable": tables}[el.tag][int(el.get("id"))] = cur_list
        else:
            if el.tag == "trophyListEntry" and el.get("itemId"):
                cur_list.append((float(el.get("dropFrequency")),
                                 int(el.get("itemId")), int(el.get("quantity") or 1)))
            elif el.tag == "treasureListEntry" and el.get("treasureGroupProfileId"):
                cur_list.append(int(el.get("treasureGroupProfileId")))
            elif el.tag == "itemsTableEntry" and el.get("itemId"):
                cur_list.append((int(el.get("itemId")), int(el.get("quantity") or 1)))
            if el.tag in ("trophyList", "treasureList", "itemsTable"):
                cur_list = None
            el.clear()

    # containers.xml join: profession-gated container objects are the nodes
    nodes = {}
    multi_table_alternatives = 0
    for _, el in ET.iterparse(os.path.join(data_dir, "containers.xml")):
        if el.tag != "container":
            continue
        cid = int(el.get("id"))
        if cid in req:
            # item id -> [min, max, best frequency]
            agg = {}

            def roll(iid, qty, freq):
                a = agg.setdefault(iid, [0, 0, 0.0])
                if freq >= 1.0:
                    a[0] += qty
                a[1] += qty
                a[2] = max(a[2], freq)

            tl = el.get("trophyListId")
            for freq, iid, qty in trophy.get(int(tl), []) if tl else []:
                roll(iid, qty, freq)
            trl = el.get("treasureListId")
            for gid in treasure.get(int(trl), []) if trl else []:
                entries = tables[gid]
                if len(entries) == 1:
                    roll(entries[0][0], entries[0][1], 1.0)
                else:
                    multi_table_alternatives += 1
                    for iid, qty in entries:
                        roll(iid, qty, 0.5)
            if agg:
                pid, tier = req[cid]
                yields = []
                for iid, (mn, mx, freq) in agg.items():
                    band = 1 if mn > 0 else (3 if freq < NODE_RARE_FREQ else 2)
                    yields.append((band, -mx, iid, mn, mx))
                yields.sort()
                nodes[cid] = (prof_key[pid], tier, yields)
        el.clear()
    print("nodes: %d (multi-item treasure tables: %d)" % (len(nodes), multi_table_alternatives))

    # localized node names -> item id (bytewise-exact target-name lookup);
    # missing localized labels fall back to the English name so lookups on
    # partially translated clients still resolve
    node_ids = sorted(nodes)
    en_lab = parse_labels(data_dir, "en", "items")
    name_parts = ["D.NAMES = {\n"]
    duplicate_names = 0
    for lang in langs:
        lab = en_lab if lang == "en" else parse_labels(data_dir, lang, "items")
        entries = {}
        for iid in node_ids:
            name = lab.get(iid) or en_lab.get(iid)
            if not name:
                raise AssertionError("node item %d has no English label" % iid)
            if name in entries:
                duplicate_names += 1
            entries[name] = iid
        name_parts.append("%s = {\n" % lang)
        for name in sorted(entries):
            name_parts.append("[%s] = %d,\n" % (lua_string(name), entries[name]))
        name_parts.append("},\n")
    name_parts.append("}\n")
    if duplicate_names:
        print("WARNING: %d duplicate node names collapsed" % duplicate_names)

    # per-node records
    node_parts = ["D.NODES = {\n"]
    for iid in node_ids:
        key, tier, yields = nodes[iid]
        ys = ", ".join("{%d, %d, %d, %d}" % (y[2], y[3], y[4], y[0]) for y in yields)
        node_parts.append('[%d] = { p = "%s", t = %d, y = { %s } },\n' % (iid, key, tier, ys))
    node_parts.append("}\n")

    # localized profession names (same source as the recipes domain)
    used_profs = {nodes[i][0] for i in node_ids}
    en_prof_lab = parse_labels(data_dir, "en", "crafting")
    prof_parts = ["D.PROFS = {\n"]
    for lang in langs:
        lab = parse_labels(data_dir, lang, "crafting")
        entries = []
        for ident, key, en_name in prof_defs:
            if key in used_profs:
                value = lab.get(ident) or en_prof_lab.get(ident) or en_name
                entries.append('["%s"] = %s' % (key, lua_string(value)))
        if len(entries) != len(used_profs):
            raise AssertionError("crafting.xml is missing professions used by nodes")
        prof_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    prof_parts.append("}\n")

    # localized crafting tier names (CraftTier enum labels)
    tier_enum = parse_enum(data_dir, "CraftTier")
    used_tiers = sorted({nodes[i][1] for i in node_ids})
    en_tier_lab = parse_labels(data_dir, "en", "enum-CraftTier", raw_keys=True)
    tier_parts = ["D.TIERS = {\n"]
    for lang in langs:
        lab = parse_labels(data_dir, lang, "enum-CraftTier", raw_keys=True)
        entries = []
        for code in used_tiers:
            enum_key = tier_enum[code]
            value = lab.get(enum_key) or en_tier_lab.get(enum_key) or enum_key
            entries.append("[%d] = %s" % (code, lua_string(value)))
        tier_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    tier_parts.append("}\n")

    # tier badge icon layers, professions used by nodes only
    icon_parts = ["D.ICONS = {\n"]
    for key in sorted(used_profs):
        tiers = icons[key]
        entries = []
        for tier in sorted(tiers):
            layers = ", ".join(tiers[tier].split("-"))
            entries.append("[%d] = { %s }" % (tier, layers))
        icon_parts.append('["%s"] = { %s },\n' % (key, ", ".join(entries)))
    icon_parts.append("}\n")

    size = write_file(out_dir, "nodes.lua", name_parts + node_parts + prof_parts + tier_parts + icon_parts)
    print("nodes.lua: %d bytes (%.1fs)" % (size, time.time() - t0))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True, help=".data/lore directory")
    ap.add_argument("--out", required=True, help="output directory for generated Lua")
    ap.add_argument("--db", default="items,recipes", help="comma list: items,recipes,bestiary,nodes")
    ap.add_argument("--langs", default=",".join(LANGS))
    ap.add_argument("--bestiary-json",
                    default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                         os.pardir, os.pardir, ".tools",
                                         "bestiary_source.json"),
                    help="JSON produced by bestiary_dump.lua from src/Encyclopedia/data.lua")
    args = ap.parse_args()
    langs = args.langs.split(",")
    for db in args.db.split(","):
        if db == "items":
            convert_items(args.data, os.path.join(args.out, "Items"), langs)
        elif db == "recipes":
            convert_recipes(args.data, os.path.join(args.out, "Recipes"), langs)
        elif db == "bestiary":
            convert_bestiary(args.bestiary_json, os.path.join(args.out, "Bestiary"), args.data)
        elif db == "nodes":
            convert_nodes(args.data, os.path.join(args.out, "Nodes"), langs)
        else:
            raise SystemExit("unknown db: " + db)


if __name__ == "__main__":
    main()
