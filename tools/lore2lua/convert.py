def parse_items(data_dir):
    path = os.path.join(data_dir, "items.xml")
    items = {}
    for _, el in ET.iterparse(path):
        if el.tag == "item":
            key = int(el.get("key"))
            items[key] = (
                el.get("quality"),
                int(el.get("level") or 0),
                int(el.get("class") or 0),
                el.get("category"),
                el.get("slot"),
                el.get("icon"),
                el.get("name"),
                int(el.get("minLevel") or 0),
                el.get("requiredClass"),
                int(el.get("maxLevel") or 0),
            )
            el.clear()
    return items


def items_from_records(records):
    """Game-extracted item records ({id: {field: value}}, from
    tools/data-extractor/extract_items.py): same tuples as parse_items,
    plus per-language names ({id: {lang: name}})."""
    items, names = {}, {}
    for key, v in records.items():
        items[int(key)] = (
            v.get("quality"),
            v.get("level") or 0,
            v.get("class") or 0,
            v.get("category"),
            v.get("slot"),
            v.get("icon"),
            v.get("name"),
            v.get("minLevel") or 0,
            v.get("requiredClass"),
            v.get("maxLevel") or 0,
        )
        names[int(key)] = {k[5:]: val for k, val in v.items()
                           if k.startswith("name_")}
    return items, names


def build_names_by_lang_records(json_names, langs, ids, en_fallback):
    """build_names_by_lang equivalent fed from extractor records."""
    en_names, missing_en = [], 0
    for n, i in enumerate(ids):
        name = en_fallback[n]
        if name is None:
            missing_en += 1
            name = ""
        en_names.append(name)
    names_by_lang, baked_report = {}, {}
    for lang in langs:
        if lang == "en":
            names_by_lang[lang] = en_names
            baked_report[lang] = 0
            continue
        names, baked = [], 0
        for n, i in enumerate(ids):
            v = json_names.get(i, {}).get(lang)
            if v is None or v == "":
                v = en_names[n]
                baked += 1
            names.append(v)
        names_by_lang[lang] = names
        baked_report[lang] = baked
    return names_by_lang, baked_report, missing_en


def parse_traceries(data_dir):
    """item id -> (socket type, min LI item level, max LI item level,
    uniqueness channel)."""
    traceries = {}
    for _, el in ET.iterparse(os.path.join(data_dir, "traceries.xml")):
        if el.tag == "tracery":
            traceries[int(el.get("itemId"))] = (
                int(el.get("type")),
                int(el.get("minItemLevel") or 0),
                int(el.get("maxItemLevel") or 0),
                int(el.get("uniquenessChannel") or 0),
            )
    return traceries


BUCKETS = ["equipment", "consumable", "resource", "housing", "tracery"]
EQUIP_CATS = {"ARMOUR", "WEAPON", "LEGENDARY_ITEM", "LEGENDARY_ITEM2",
              "LEGENDARY_WEAPON", "LEGENDARY_WEAPON2", "ESSENCE"}
CONSUME_KW = ("food", "drink", "potion", "draught", "salve", "scroll of",
              "battle scroll", "hope token", "firework", "festival token",
              "tomes", "perks", "pipeweed")
RESOURCE_KW = ("resource", "ingredient", "craft", "component", "relic",
               "tool", "dye", "device", "trophy")


def _classify_items(items, data_dir, aux=None):
    """id -> bucket code (0 = not browsable). Priority: equipment >
    consumable > resource > housing; authoritative sources before keyword
    heuristics. Recipe scrolls are consumables (you use them to learn);
    the runtime groups their per-tier classes into one Type filter entry."""
    if aux is not None:
        consumable_ids = aux["consumable_ids"]
        recipes = aux["recipes"]
        cls_name = {code: label.lower()
                    for code, label in aux["class_labels"]["en"].items()}
        tracery_ids = set(aux["traceries"])
    else:
        consumable_ids = set()
        for _, el in ET.iterparse(os.path.join(data_dir, "consumables.xml")):
            if el.tag == "consumable":
                consumable_ids.add(int(el.get("identifier")))
                el.clear()
        recipes = parse_recipes(data_dir)
        cls_enum = parse_enum(data_dir, "ItemClass")
        cls_lab = parse_labels(data_dir, "en", "enum-ItemClass", raw_keys=True)
        cls_name = {code: (cls_lab.get(k) or k).lower()
                    for code, k in cls_enum.items()}
        tracery_ids = set(parse_traceries(data_dir))

    resource_ids = set()
    scroll_ids = set()
    for r in recipes.values():
        if r["pack"]:
            resource_ids.add(r["pack"])
        if r["scroll"]:
            scroll_ids.add(r["scroll"])
        for v in r["versions"]:
            for iid, _q in v["ing"]:
                resource_ids.add(iid)
            for iid, _q, _b in v["opt"]:
                resource_ids.add(iid)

    buckets = {}
    counts = {"equipment": 0, "consumable": 0, "resource": 0, "housing": 0,
              "tracery": 0, "other": 0}
    for iid, it in items.items():
        _q, _lvl, cls, cat, slot, _icon, _name, _minlvl, _reqcls, _maxlvl = it
        label = cls_name.get(cls, "")
        if iid in tracery_ids:
            bucket = 5
        elif slot is not None or cat in EQUIP_CATS:
            bucket = 1
        elif (iid in consumable_ids or iid in scroll_ids
              or label.startswith("recipe")
              or any(k in label for k in CONSUME_KW)):
            bucket = 2
        elif iid in resource_ids or any(k in label for k in RESOURCE_KW):
            bucket = 3
        elif label.startswith("home:"):
            bucket = 4
        else:
            bucket = 0
        buckets[iid] = bucket
        counts[BUCKETS[bucket - 1] if bucket else "other"] += 1
    print("buckets:", counts)
    return buckets


def convert_items(data_dir, out_dir, langs, records=None, aux=None):
    """records/aux: in-memory game-extracted data (tools/data-extractor);
    when None, the legacy XML dumps from data_dir are used."""
    t0 = time.time()
    json_names = None
    if records is not None:
        items, json_names = items_from_records(records)
    else:
        items = parse_items(data_dir)
    ids = sorted(items)
    count = len(ids)
    print("parsed items: %d records (%.1fs)" % (count, time.time() - t0))
    bucket_by_id = _classify_items(items, data_dir, aux)

    def enum_table(idx):
        values = sorted({v[idx] for v in items.values() if v[idx] is not None})
        return values, {v: i + 1 for i, v in enumerate(values)}

    quality_vals, quality_code = enum_table(0)
    category_vals, category_code = enum_table(3)
    slot_vals, slot_code = enum_table(4)

    pool_vals = sorted({v[5] for v in items.values() if v[5] is not None})
    pool_code = {v: i + 1 for i, v in enumerate(pool_vals)}
    print("icon pool: %d unique composites" % len(pool_vals))

    coded = []
    for i in ids:
        q, lvl, cls, cat, slot, icon, _name, min_level, _reqcls, _maxlvl = items[i]
        coded.append((
            quality_code.get(q, 0), lvl, cls, category_code.get(cat, 0),
            slot_code.get(slot, 0), pool_code.get(icon, 0), min_level,
            bucket_by_id[i],
        ))

    base_id = ids[0]
    id_width = width_for(ids[-1] - base_id)
    field_names = ["quality", "level", "class", "category", "slot", "icon", "min_level", "bucket"]
    n_fields = len(field_names)
    widths = [width_for(max(c[k] for c in coded)) for k in range(n_fields)]
    stride = sum(widths)

    ids_blob = "".join(b93(i - base_id, id_width) for i in ids)
    rec_blob = "".join(
        "".join(b93(c[k], widths[k]) for k in range(n_fields)) for c in coded
    )

    pool_blob = "".join(pool_vals)
    poff, p = [], 1
    for v in pool_vals:
        poff.append(p)
        p += len(v)
    poff.append(p)
    poff_width = width_for(p)
    poff_blob = "".join(b93(x, poff_width) for x in poff)

    for n, i in enumerate(ids):
        pos = n * stride
        at = 0
        for k in range(n_fields):
            if u93(rec_blob, pos + at, widths[k]) != coded[n][k]:
                raise AssertionError("round-trip mismatch id %d field %d" % (i, k))
            at += widths[k]
        if u93(ids_blob, n * id_width, id_width) != i - base_id:
            raise AssertionError("round-trip mismatch in IDS at %d" % i)
    print("round-trip: all %d records verified" % count)

    os.makedirs(out_dir, exist_ok=True)
    sizes = {}
    sizes["records.lua"] = write_file(out_dir, "records.lua", [
        emit_blob("IDS", ids_blob),
        emit_blob("REC", rec_blob),
        emit_blob("POOL", pool_blob),
        emit_blob("POFF", poff_blob),
    ])

    en_fallback = [items[i][6] for i in ids]
    if json_names is not None:
        names_by_lang, baked_report, missing_en = build_names_by_lang_records(
            json_names, langs, ids, en_fallback)
    else:
        names_by_lang, baked_report, missing_en = build_names_by_lang(
            data_dir, "items", langs, ids, en_fallback)
    # bucket-0 ("other") items are never text-searched: the Encyclopedia
    # searches within the browsable bucket lists only, so their folded
    # search text is dead weight (~35% of the blob)
    search_mask = [bucket_by_id[i] != 0 for i in ids]
    lang_sizes, _ = emit_lang_files(out_dir, ids, names_by_lang, langs, search_mask)
    sizes.update(lang_sizes)

    # localized ItemClass names (used codes only) + per-bucket class lists
    used_classes = sorted({items[i][2] for i in ids})
    if aux is not None:
        class_labels = aux["class_labels"]
        en_class_label = class_labels["en"]
    else:
        cls_enum = parse_enum(data_dir, "ItemClass")
        en_cls = parse_labels(data_dir, "en", "enum-ItemClass", raw_keys=True)
        # labels are keyed by the enum name whether it is a "key:..."
        # reference or a literal ("WoPower" -> "Word of Power"); always
        # prefer the localized label
        class_labels = {}
        for lang in langs:
            lab = parse_labels(data_dir, lang, "enum-ItemClass", raw_keys=True)
            class_labels[lang] = {
                code: (lab.get(key) or en_cls.get(key) or key)
                for code, key in cls_enum.items()}
        en_class_label = class_labels["en"]
    unlabeled = [c for c in used_classes if c and c not in en_class_label]
    if unlabeled:
        print("WARNING: %d item classes missing from ItemClass enum" % len(unlabeled))
    cls_parts = ["D.CLASSES = {\n"]
    for lang in langs:
        entries = []
        for code in used_classes:
            value = class_labels[lang].get(code)
            if value is None:
                value = en_class_label.get(code)
            if value is not None:
                entries.append("[%d]=%s" % (code, lua_string(value)))
        cls_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    cls_parts.append("}\n")

    # official localized quality names, keyed by the tuple's enum strings
    # (the game displays LEGENDARY as "Epic"/"Epos" etc. -- never hand-write
    # these)
    if aux is not None:
        quality_labels = aux["quality_labels"]
        quality_keys = sorted(quality_labels["en"])
    else:
        quality_entries = []
        for _, el in ET.iterparse(os.path.join(data_dir, "enums", "ItemQuality.xml")):
            if el.tag == "entry":
                quality_entries.append((el.get("key"), el.get("name")))
        en_quality = parse_labels(data_dir, "en", "enum-ItemQuality", raw_keys=True)
        quality_labels = {}
        for lang in langs:
            lab = parse_labels(data_dir, lang, "enum-ItemQuality", raw_keys=True)
            quality_labels[lang] = {
                qkey: (lab.get(label_key) or en_quality.get(label_key) or qkey)
                for qkey, label_key in quality_entries}
        quality_keys = [qkey for qkey, _ in quality_entries]
    cls_parts.append("D.QUALITIES = {\n")
    for lang in langs:
        entries = []
        for qkey in quality_keys:
            value = quality_labels[lang].get(qkey) or quality_labels["en"].get(qkey) or qkey
            entries.append('["%s"] = %s' % (qkey, lua_string(value)))
        cls_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    cls_parts.append("}\n")

    bucket_classes = {b: set() for b in range(1, len(BUCKETS) + 1)}
    for i in ids:
        b = bucket_by_id[i]
        if b:
            bucket_classes[b].add(items[i][2])
    cls_parts.append("D.BUCKET_CLASSES = {\n")
    for b in range(1, len(BUCKETS) + 1):
        cls_parts.append("%s = { %s },\n" % (
            BUCKETS[b - 1], ", ".join(str(c) for c in sorted(bucket_classes[b]))))
    cls_parts.append("}\n")

    # per-tier recipe classes ("Recipe: Weaponsmith Tier 9", ~100 codes):
    # the Type dropdown shows them as one grouped "Recipes" entry
    recipe_class_codes = sorted(
        c for c in bucket_classes[2]
        if en_class_label.get(c, "").lower().startswith("recipe"))
    cls_parts.append("D.RECIPE_CLASSES = { %s }\n" % ", ".join(
        str(c) for c in recipe_class_codes))

    # per-language, per-bucket class-code order for the Type dropdown,
    # sorted by the localized label (recipe classes excluded: the
    # browser inserts their grouped entry itself; unlabeled codes
    # excluded: the dropdown never shows them)
    recipe_class_set = set(recipe_class_codes)
    cls_parts.append("D.CLASS_ORDER = {\n")
    for lang in langs:
        def class_label(code):
            return class_labels[lang].get(code) or en_class_label.get(code)
        bucket_parts = []
        for b in range(1, len(BUCKETS) + 1):
            codes = [c for c in bucket_classes[b]
                     if c and c not in recipe_class_set
                     and class_label(c) is not None]
            codes.sort(key=lambda c: (fold(display_sort_text(class_label(c))),
                                      class_label(c), c))
            bucket_parts.append("%s = { %s }" % (
                BUCKETS[b - 1], ", ".join(str(c) for c in codes)))
        cls_parts.append("%s = { %s },\n" % (lang, ", ".join(bucket_parts)))
    cls_parts.append("}\n")

    # runtime fold map: non-ASCII chars -> folded ascii, so typed needles
    # fold exactly like the build-time search blobs
    fold_pairs = {}
    for lang in langs:
        for name in names_by_lang[lang]:
            for ch in name:
                if ord(ch) >= 128:
                    f = fold(ch)
                    if f != ch:
                        fold_pairs[ch] = f
    cls_parts.append("D.FOLD = {\n")
    for ch in sorted(fold_pairs):
        cls_parts.append("[%s] = %s,\n" % (lua_string(ch), lua_string(fold_pairs[ch])))
    cls_parts.append("}\n")
    sizes["classes.lua"] = write_file(out_dir, "classes.lua", cls_parts)

    # per-language, per-bucket ordinal permutations sorted by display label
    # (folded-alphabetical): tab listings iterate these, zero runtime sorting
    bucket_ord_w = width_for(count)
    for lang in langs:
        names = names_by_lang[lang]
        parts = ["D.ord_width = %d\n" % bucket_ord_w]
        for b in range(1, len(BUCKETS) + 1):
            ordinals = [n + 1 for n, i in enumerate(ids) if bucket_by_id[i] == b]
            ordinals.sort(key=lambda o: (fold(display_sort_text(names[o - 1])),
                                         names[o - 1]))
            parts.append(emit_blob("B_" + BUCKETS[b - 1].upper(),
                                   "".join(b93(o, bucket_ord_w) for o in ordinals)))
        sizes["buckets_%s.lua" % lang] = write_file(out_dir, "buckets_%s.lua" % lang, parts)

    # tracery metadata side table: per tracery ordinal the LI item-level
    # band it sockets into, the uniqueness channel and the player class
    # (requiredClass attr; socket type 21 is Mariner, added without the
    # attr). Sorted ordinal keys + fixed stride, bsearch at runtime.
    if aux is not None:
        traceries = aux["traceries"]
        # class enum: EN labels are the requiredClass key strings
        player_class_labels = aux["player_class_labels"]
        class_id_by_name = {label: code for code, label
                            in player_class_labels["en"].items()}
        class_en_names = player_class_labels["en"]
    else:
        traceries = parse_traceries(data_dir)
        class_defs = []
        for _, el in ET.iterparse(os.path.join(data_dir, "classes.xml")):
            if el.tag == "class" and el.get("key"):
                class_defs.append((int(el.get("id")), el.get("key"), el.get("name")))
        class_id_by_name = {}
        for cid, ckey, cname in class_defs:
            class_id_by_name[ckey] = cid
            class_id_by_name[cname] = cid

    entries = []
    used_class_ids = []
    class_idx_by_id = {}
    for n, i in enumerate(ids):
        info = traceries.get(i)
        if info is None:
            continue
        ttype, min_il, max_il, channel = info
        req = items[i][8]
        if req is None and ttype == 21:
            req = "Mariner"
        class_idx = 0
        if req is not None:
            cid = class_id_by_name[req]
            if class_idx_by_id.get(cid) is None:
                used_class_ids.append(cid)
                class_idx_by_id[cid] = len(used_class_ids)
            class_idx = class_idx_by_id[cid]
        # max usable character level (min is the records' min_level field);
        # min_il is the tracery's base iLvl, max_il its enhancement cap
        entries.append((n + 1, min_il, max_il, channel, class_idx, items[i][9]))

    il_w = width_for(max(max(e[2] for e in entries), 1))
    ch_w = width_for(max(max(e[3] for e in entries), 1))
    t_parts = [
        "D.count = %d\n" % len(entries),
        "D.ord_width = %d\n" % bucket_ord_w,
        "D.il_width = %d\n" % il_w,
        "D.ch_width = %d\n" % ch_w,
        emit_blob("T_ORD", "".join(b93(e[0], bucket_ord_w) for e in entries)),
        emit_blob("T_REC", "".join(
            b93(e[1], il_w) + b93(e[2], il_w) + b93(e[3], ch_w) + b93(e[4], 1) + b93(e[5], il_w)
            for e in entries)),
    ]
    # localized player class names, indexed by the per-entry class index
    t_parts.append("D.CLASSES = {\n")
    if aux is not None:
        for lang in langs:
            names = [lua_string(player_class_labels[lang].get(cid)
                                or class_en_names[cid])
                     for cid in used_class_ids]
            t_parts.append("%s = { %s },\n" % (lang, ", ".join(names)))
    else:
        en_class_lab = parse_labels(data_dir, "en", "classes")
        for lang in langs:
            lab = parse_labels(data_dir, lang, "classes")
            names = []
            for cid in used_class_ids:
                names.append(lua_string(lab.get(cid) or en_class_lab.get(cid)
                                        or [d for d in class_defs if d[0] == cid][0][2]))
            t_parts.append("%s = { %s },\n" % (lang, ", ".join(names)))
    t_parts.append("}\n")
    sizes["traceries.lua"] = write_file(out_dir, "traceries.lua", t_parts)
    print("traceries side table: %d entries, %d classes" % (len(entries), len(used_class_ids)))

    sizes["manifest.lua"] = write_file(out_dir, "manifest.lua", [
        "D.count = %d\n" % count,
        "D.base_id = %d\n" % base_id,
        "D.id_width = %d\n" % id_width,
        "D.stride = %d\n" % stride,
        "D.poff_width = %d\n" % poff_width,
        "D.fields = { %s }\n" % ", ".join(lua_string(f) for f in field_names),
        "D.widths = { %s }\n" % ", ".join(str(w) for w in widths),
        "D.enums = {\n"
        + "quality = { %s },\n" % ", ".join(lua_string(v) for v in quality_vals)
        + "category = { %s },\n" % ", ".join(lua_string(v) for v in category_vals)
        + "slot = { %s },\n" % ", ".join(lua_string(v) for v in slot_vals)
        + "}\n",
        "D.langs = { %s }\n" % ", ".join(lua_string(v) for v in langs),
    ])
    print_report(baked_report, missing_en, sizes, langs, count, t0)


