#!/usr/bin/env python3
"""lore2lua: convert lore sources into packed-string Lua databases.

Domains: items, recipes (extracted from the game client by
tools/data-extractor/extract.py, which calls convert_items /
convert_recipes in-process with in-memory records) and bestiary
(the wiki database). Stdlib only.

Usage:
  python3 tools/data-extractor/extract.py <game_dir>        # items + recipes
  lua5.4 .tools/bestiary_dump.lua . .tools/bestiary_source.json
  python3 tools/lore2lua/convert.py --data <lore_dir> --out src/Data --db bestiary

Bestiary pipeline (local tooling in .tools/): browser_bestiary_dump.js
fetches the wiki (raw dump JSON); src/Encyclopedia/data.lua is the
maintained entry database built from it; bestiary_dump.lua + this packer
turn data.lua into the packed blobs the plugin actually loads
(src/Data/Bestiary). data.lua itself is no longer imported at runtime --
it is the packing source. NOTE: bestiary (and nodes) still read the
legacy XML layout from --data; porting them to game extraction is
pending (see tools/data-extractor/README.md).
"""
