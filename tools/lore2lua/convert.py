import unicodedata
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from codec import b93, u93, width_for, emit_blob  # noqa: E402

LANGS = ["de", "en", "es", "fr", "ru"]
ITEM_BASE = 1879000000
GENERATED_HEADER = (
    "-- GENERATED by LUI data tools -- DO NOT EDIT\n"
    "-- Source: LOTRO game client data\n"
)


def fold(name):
    """Search normalization: lowercase + strip combining accents (é -> e)."""
    out = []
    for ch in unicodedata.normalize("NFD", name.lower()):
        if not unicodedata.combining(ch):
            out.append(ch)
    return unicodedata.normalize("NFC", "".join(out))


_TEMPLATE_REF = re.compile(r"\$\{([^}:|]*)(?::([^}|]*)[^}]*)?\}")
_GENDER_TAGS = re.compile(r"\[[^\]]*\]")


def display_sort_text(label):
    """Collation text for a display label: gender templates ${VAR:a|b}
    sort as their first variant, bare ${VAR} refs as nothing ('$' would
    otherwise clump every templated name before all plain names)."""
    if "${" not in label:
        return label
    text = _TEMPLATE_REF.sub(lambda m: m.group(2) or "", label)
    return _GENDER_TAGS.sub("", text)


def parse_labels(data_dir, lang, db, raw_keys=False):
    path = os.path.join(data_dir, "labels", lang, db + ".xml")
    labels = {}
    if not os.path.exists(path):
        return labels
    for _, el in ET.iterparse(path):
        if el.tag == "label":
            key = el.get("key")
            if raw_keys:
                labels[key] = el.get("value")
            elif key.isdigit():
                labels[int(key)] = el.get("value")
            el.clear()
    return labels


def parse_enum(data_dir, name):
    """enums/<name>.xml -> { code: label-key-or-literal }"""
    path = os.path.join(data_dir, "enums", name + ".xml")
    entries = {}
    for _, el in ET.iterparse(path):
        if el.tag == "entry":
            entries[int(el.get("code"))] = el.get("name")
    return entries


def lua_string(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_file(out_dir, name, parts):
    """Emit a data module usable both by Turbine `import` (registers into the
    _G.LoreData namespace) and by standalone `dofile` (returns the table)."""
    path = os.path.join(out_dir, name)
    domain = os.path.basename(out_dir)
    reg_key = "%s.%s" % (domain, name[:-4])
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(GENERATED_HEADER)
        f.write("local D = {}\n")
        for p in parts:
            f.write(p)
        f.write('_G.LoreData = _G.LoreData or {}\n')
        f.write('_G.LoreData[%s] = D\n' % lua_string(reg_key))
        f.write("return D\n")
    return os.path.getsize(path)


def byte_len(s):
    return len(s.encode("utf-8"))


def build_names_by_lang(data_dir, db, langs, ids, en_fallback):
    """Per-language display names aligned to ids; en baked in where missing."""
    labels_en = parse_labels(data_dir, "en", db)
    en_names, missing_en = [], 0
    for n, i in enumerate(ids):
        name = labels_en.get(i) or en_fallback[n]
        if name is None:
            missing_en += 1
            name = ""
        en_names.append(name)

    names_by_lang, baked_report = {}, {}
    for lang in langs:
        if lang == "en":
            names_by_lang[lang] = en_names
            baked_report[lang] = 0
            continue
        lab = parse_labels(data_dir, lang, db)
        names, baked = [], 0
        for n, i in enumerate(ids):
            v = lab.get(i)
            if v is None or v == "":
                v = en_names[n]
                baked += 1
            names.append(v)
        names_by_lang[lang] = names
        baked_report[lang] = baked
    return names_by_lang, baked_report, missing_en


# a 2-char needle matching more than this share of a domain's entries is
# baked into D.STOP2 and treated as "still typing" by the runtime
STOP2_SHARE = 0.05


def emit_lang_files(out_dir, ids, names_by_lang, langs, search_mask=None):
    """labels_<lang> (LBL/LOFF), names_<lang> (NAME/NOFF, sorted) and search_<lang> (SRCH/SOFF) per language.

    search_mask: optional list of booleans aligned to ids; False entries get
    empty folded search text (offsets stay aligned, the entry just never
    matches). Used to keep never-searched records out of the search blobs."""
    count = len(ids)
    ord_width = width_for(count)
    sizes = {}
    for lang in langs:
        names = names_by_lang[lang]

        lbl_blob = "".join(names)
        loff, p = [], 1
        for v in names:
            loff.append(p)
            p += byte_len(v)
        loff.append(p)
        loff_width = width_for(p)
        loff_blob = "".join(b93(x, loff_width) for x in loff)
        sizes["labels_%s.lua" % lang] = write_file(out_dir, "labels_%s.lua" % lang, [
            "D.loff_width = %d\n" % loff_width,
            emit_blob("LBL", lbl_blob),
            emit_blob("LOFF", loff_blob),
        ])

        by_name = {}
        for n, v in enumerate(names):
            if v and "\t" not in v and "\n" not in v:
                by_name.setdefault(v, []).append(n + 1)
        sorted_names = sorted(by_name)
        parts, noffs, p = [], [], 1
        for v in sorted_names:
            entry = "\n%s\t%s" % (v, "".join(b93(o, ord_width) for o in by_name[v]))
            noffs.append(p)
            parts.append(entry)
            p += byte_len(entry)
        name_blob = "".join(parts) + "\n"
        noff_width = width_for(p)
        noff_blob = "".join(b93(x, noff_width) for x in noffs)
        sizes["names_%s.lua" % lang] = write_file(out_dir, "names_%s.lua" % lang, [
            "D.ord_width = %d\n" % ord_width,
            "D.noff_width = %d\n" % noff_width,
            "D.entry_count = %d\n" % len(sorted_names),
            emit_blob("NAME", name_blob),
            emit_blob("NOFF", noff_blob),
        ])

        # type-ahead search blob: folded names in ordinal order + offsets
        folded = [fold(v) if search_mask is None or search_mask[n] else ""
                  for n, v in enumerate(names)]
        srch_blob = "\n".join(folded)
        soff, p = [], 1
        for v in folded:
            soff.append(p)
            p += byte_len(v) + 1
        soff.append(p)
        soff_width = width_for(p)
        soff_blob = "".join(b93(x, soff_width) for x in soff)
        # stop bigrams: 2-char needles matching more than STOP2_SHARE of
        # the entries. A cold runtime seed scan for one of those costs
        # tens of ms and filters out nearly nothing, so evaluate_domain
        # treats them as "still typing" instead of scanning
        bigram_hits = {}
        for text in folded:
            entry_bigrams = set()
            data = text.encode("utf-8")
            for k in range(len(data) - 1):
                pair = data[k:k + 2]
                # printable ASCII only: multi-byte pairs never get close
                # to the share threshold and would need encoding care
                if 32 <= pair[0] <= 126 and 32 <= pair[1] <= 126:
                    entry_bigrams.add(pair)
            for bigram in entry_bigrams:
                bigram_hits[bigram] = bigram_hits.get(bigram, 0) + 1
        threshold = len(folded) * STOP2_SHARE
        stop2 = sorted(b for b, hits in bigram_hits.items() if hits > threshold)
        sizes["search_%s.lua" % lang] = write_file(out_dir, "search_%s.lua" % lang, [
            "D.soff_width = %d\n" % soff_width,
            emit_blob("SRCH", srch_blob),
            emit_blob("SOFF", soff_blob),
            "D.STOP2 = { %s }\n" % ", ".join(
                "[%s]=true" % lua_string(b.decode("ascii")) for b in stop2),
        ])

    return sizes, ord_width


def print_report(baked_report, missing_en, sizes, langs, count, t0):
    if missing_en:
        print("WARNING: %d records have no en label at all" % missing_en)
    print("label fallback baked from en:")
    for lang in langs:
        if lang != "en":
            print("  %s: %d of %d" % (lang, baked_report[lang], count))
    print("emitted files:")
    total = 0
    for name in sorted(sizes):
        total += sizes[name]
        print("  %-18s %8.2f MB" % (name, sizes[name] / 1e6))
    print("  %-18s %8.2f MB" % ("TOTAL", total / 1e6))
    print("done in %.1fs\n" % (time.time() - t0))


