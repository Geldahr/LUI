def parse_recipes(data_dir):
    path = os.path.join(data_dir, "recipes.xml")
    recipes = {}
    for _, el in ET.iterparse(path):
        if el.tag == "recipe":
            rid = int(el.get("id"))
            r = {
                "name": el.get("name"),
                "profession": el.get("profession"),
                "tier": int(el.get("tier")),
                "category": int(el.get("category") or 0),
                "xp": int(el.get("xp") or 0),
                "cooldown": int(el.get("cooldown") or 0),
                "guild": el.get("guild") == "true",
                "single_use": el.get("singleUse") == "true",
                "scroll": 0, "pack": 0, "pack_count": 0,
                "versions": [],
            }
            sc = el.find("scrollItem")
            if sc is not None:
                r["scroll"] = int(sc.get("itemId"))
            ip = el.find("ingredientPack")
            if ip is not None:
                r["pack"] = int(ip.get("itemId"))
                r["pack_count"] = int(ip.get("count") or 1)
            for rr in el.findall("recipeResult"):
                v = {"crit": int(rr.get("baseCriticalChance") or 0),
                     "ing": [], "opt": [], "res": [], "cres": []}
                for ing in rr.findall("ingredient"):
                    it = ing.find("ingredientItem")
                    iid = int(it.get("itemId"))
                    qty = int(ing.get("quantity") or 1)
                    if ing.get("optional") == "true":
                        v["opt"].append((iid, qty, int(ing.get("criticalChanceBonus") or 0)))
                    else:
                        v["ing"].append((iid, qty))
                for res in rr.findall("result"):
                    it = res.find("resultItem")
                    iid = int(it.get("itemId"))
                    qty = int(res.get("quantity") or 1)
                    if res.get("critical") == "true":
                        v["cres"].append((iid, qty))
                    else:
                        v["res"].append((iid, qty))
                r["versions"].append(v)
            recipes[rid] = r
            el.clear()
    return recipes


def convert_recipes(data_dir, out_dir, langs, records=None, aux=None):
    t0 = time.time()
    recipes = records if records is not None else parse_recipes(data_dir)
    ids = sorted(recipes)
    count = len(ids)
    print("parsed recipes: %d records (%.1fs)" % (count, time.time() - t0))

    # Flag reciprocal conversion recipes (craft-XP "scraps"/processing pairs):
    # recipe A produces X from Y while recipe B produces Y from X. These form
    # 2-cycles in the crafting graph; the runtime must never expand material
    # trees through them.
    producers = {}
    for rid, r in recipes.items():
        for v in r["versions"]:
            ings = {i for i, _q in v["ing"]}
            for res_item, _q in v["res"]:
                producers.setdefault(res_item, []).append((rid, ings))
    conversion_count = 0
    for rid, r in recipes.items():
        conv = False
        for v in r["versions"]:
            results = {i for i, _q in v["res"]}
            for ing, _q in v["ing"]:
                for rid2, ings2 in producers.get(ing, []):
                    if rid2 != rid and ings2 & results:
                        conv = True
        r["conversion"] = conv
        if conv:
            conversion_count += 1
    print("conversion (2-cycle) recipes flagged: %d" % conversion_count)

    profession_vals = sorted({r["profession"] for r in recipes.values()})
    profession_code = {v: i + 1 for i, v in enumerate(profession_vals)}

    def item_off(iid):
        if iid == 0:
            return 0
        off = iid - ITEM_BASE
        if off <= 0:
            raise AssertionError("item id %d below base" % iid)
        return off

    # width maxes over the whole domain
    mx = {"category": 0, "xp": 0, "cooldown": 0, "item": 0, "qty": 0,
          "bonus": 0, "crit": 0, "n": 0, "pack_count": 0, "tier": 0}
    for r in recipes.values():
        mx["category"] = max(mx["category"], r["category"])
        mx["xp"] = max(mx["xp"], r["xp"])
        mx["cooldown"] = max(mx["cooldown"], r["cooldown"])
        mx["tier"] = max(mx["tier"], r["tier"])
        mx["pack_count"] = max(mx["pack_count"], r["pack_count"])
        mx["item"] = max(mx["item"], item_off(r["scroll"]), item_off(r["pack"]))
        mx["n"] = max(mx["n"], len(r["versions"]))
        for v in r["versions"]:
            mx["crit"] = max(mx["crit"], v["crit"])
            mx["n"] = max(mx["n"], len(v["ing"]), len(v["opt"]), len(v["res"]), len(v["cres"]))
            for iid, q in v["ing"] + v["res"] + v["cres"]:
                mx["item"] = max(mx["item"], item_off(iid))
                mx["qty"] = max(mx["qty"], q)
            for iid, q, b in v["opt"]:
                mx["item"] = max(mx["item"], item_off(iid))
                mx["qty"] = max(mx["qty"], q)
                mx["bonus"] = max(mx["bonus"], b)
    if min(r["cooldown"] for r in recipes.values()) < 0:
        raise AssertionError("negative cooldown found; add bias handling")

    W = {
        "profession": width_for(len(profession_vals)),
        "tier": width_for(mx["tier"]),
        "category": width_for(mx["category"]),
        "xp": width_for(mx["xp"]),
        "cooldown": width_for(mx["cooldown"]),
        "flags": 1,
        "item": width_for(mx["item"]),
        "qty": width_for(mx["qty"]),
        "bonus": width_for(mx["bonus"]),
        "crit": width_for(mx["crit"]),
        "n": width_for(mx["n"]),
        "pack_count": width_for(mx["pack_count"]),
    }

    def encode_recipe(r):
        parts = [
            b93(profession_code[r["profession"]], W["profession"]),
            b93(r["tier"], W["tier"]),
            b93(r["category"], W["category"]),
            b93(r["xp"], W["xp"]),
            b93(r["cooldown"], W["cooldown"]),
            b93((1 if r["guild"] else 0) + (2 if r["single_use"] else 0)
                + (4 if r["conversion"] else 0), W["flags"]),
            b93(item_off(r["scroll"]), W["item"]),
            b93(item_off(r["pack"]), W["item"]),
            b93(r["pack_count"], W["pack_count"]),
            b93(len(r["versions"]), W["n"]),
        ]
        for v in r["versions"]:
            parts.append(b93(v["crit"], W["crit"]))
            parts.append(b93(len(v["ing"]), W["n"]))
            parts.append(b93(len(v["opt"]), W["n"]))
            parts.append(b93(len(v["res"]), W["n"]))
            parts.append(b93(len(v["cres"]), W["n"]))
            for iid, q in v["ing"]:
                parts.append(b93(item_off(iid), W["item"]) + b93(q, W["qty"]))
            for iid, q, b in v["opt"]:
                parts.append(b93(item_off(iid), W["item"]) + b93(q, W["qty"]) + b93(b, W["bonus"]))
            for iid, q in v["res"]:
                parts.append(b93(item_off(iid), W["item"]) + b93(q, W["qty"]))
            for iid, q in v["cres"]:
                parts.append(b93(item_off(iid), W["item"]) + b93(q, W["qty"]))
        return "".join(parts)

    encoded = [encode_recipe(recipes[i]) for i in ids]
    data_blob = "".join(encoded)
    offs, p = [], 1
    for e in encoded:
        offs.append(p)
        p += len(e)
    offs.append(p)
    off_width = width_for(p)
    off_blob = "".join(b93(x, off_width) for x in offs)

    base_id = ids[0]
    id_width = width_for(ids[-1] - base_id)
    ids_blob = "".join(b93(i - base_id, id_width) for i in ids)

    # python round-trip: decode everything back and compare
    def decode_recipe(pos):
        def take(w):
            nonlocal pos
            v = u93(data_blob, pos, w)
            pos += w
            return v
        out = {
            "profession": profession_vals[take(W["profession"]) - 1],
            "tier": take(W["tier"]), "category": take(W["category"]),
            "xp": take(W["xp"]), "cooldown": take(W["cooldown"]),
        }
        flags = take(W["flags"])
        out["guild"] = flags % 2 == 1
        out["single_use"] = flags % 4 >= 2
        out["conversion"] = flags >= 4
        sc = take(W["item"])
        pk = take(W["item"])
        out["scroll"] = sc and sc + ITEM_BASE or 0
        out["pack"] = pk and pk + ITEM_BASE or 0
        out["pack_count"] = take(W["pack_count"])
        out["versions"] = []
        for _ in range(take(W["n"])):
            v = {"crit": take(W["crit"]), "ing": [], "opt": [], "res": [], "cres": []}
            ni, no, nr, nc = take(W["n"]), take(W["n"]), take(W["n"]), take(W["n"])
            for _ in range(ni):
                v["ing"].append((take(W["item"]) + ITEM_BASE, take(W["qty"])))
            for _ in range(no):
                v["opt"].append((take(W["item"]) + ITEM_BASE, take(W["qty"]), take(W["bonus"])))
            for _ in range(nr):
                v["res"].append((take(W["item"]) + ITEM_BASE, take(W["qty"])))
            for _ in range(nc):
                v["cres"].append((take(W["item"]) + ITEM_BASE, take(W["qty"])))
            out["versions"].append(v)
        return out

    for n, i in enumerate(ids):
        got = decode_recipe(offs[n] - 1)
        src = recipes[i]
        for k in ("profession", "tier", "category", "xp", "cooldown", "guild",
                  "single_use", "conversion", "scroll", "pack", "pack_count", "versions"):
            if got[k] != src[k]:
                raise AssertionError("round-trip mismatch recipe %d field %s" % (i, k))
    print("round-trip: all %d recipes verified" % count)

    os.makedirs(out_dir, exist_ok=True)
    sizes = {}
    sizes["records.lua"] = write_file(out_dir, "records.lua", [
        emit_blob("IDS", ids_blob),
        emit_blob("OFF", off_blob),
        emit_blob("DATA", data_blob),
    ])

    # Localized name chain: recipe label -> result-item label (same lang) -> en.
    # The dump only emits a recipe label when it differs from the result item's
    # name, so the item-label fallback is the game-correct localization.
    def result_item_of(r):
        for v in r["versions"]:
            if v["res"]:
                return v["res"][0][0]
            if v["cres"]:
                return v["cres"][0][0]
        return 0

    result_items = [result_item_of(recipes[i]) for i in ids]
    if records is not None:
        # records already carry the per-language chain (recipe name ->
        # result item name); bake en where a language has nothing
        en_names = [recipes[i]["name"] or "" for i in ids]
        names_by_lang, baked_report = {}, {}
        for lang in langs:
            if lang == "en":
                names_by_lang[lang] = en_names
                baked_report[lang] = 0
                continue
            names, from_en = [], 0
            for n, i in enumerate(ids):
                v = recipes[i].get("name_" + lang)
                if v is None or v == "":
                    v = en_names[n]
                    from_en += 1
                names.append(v)
            names_by_lang[lang] = names
            baked_report[lang] = from_en
    else:
        labels_en = parse_labels(data_dir, "en", "recipes")
        en_names = [labels_en.get(i) or recipes[i]["name"] for i in ids]
        names_by_lang, baked_report = {}, {}
        for lang in langs:
            if lang == "en":
                names_by_lang[lang] = en_names
                baked_report[lang] = 0
                continue
            rec_lab = parse_labels(data_dir, lang, "recipes")
            item_lab = parse_labels(data_dir, lang, "items")
            names, from_en = [], 0
            for n, i in enumerate(ids):
                v = rec_lab.get(i) or item_lab.get(result_items[n])
                if v is None or v == "":
                    v = en_names[n]
                    from_en += 1
                names.append(v)
            names_by_lang[lang] = names
            baked_report[lang] = from_en
    missing_en = sum(1 for v in en_names if not v)
    lang_sizes, _ = emit_lang_files(out_dir, ids, names_by_lang, langs)
    sizes.update(lang_sizes)

    # crafting UI category names, per language (tiny plain table)
    used_cats = {r["category"] for r in recipes.values()}
    if aux is not None:
        cat_labels = aux["category_labels"]
    else:
        cat_enum = parse_enum(data_dir, "CraftingUICategory")
        en_cat_lab = parse_labels(data_dir, "en", "enum-CraftingUICategory", raw_keys=True)
        cat_labels = {}
        for lang in langs:
            lab = parse_labels(data_dir, lang, "enum-CraftingUICategory", raw_keys=True)
            table = {}
            for code, key in cat_enum.items():
                if key.startswith("key:"):
                    table[code] = lab.get(key) or en_cat_lab.get(key) or key
                else:
                    table[code] = key
            cat_labels[lang] = table
    cat_parts = ["D.CATS = {\n"]
    for lang in langs:
        entries = []
        for code in sorted(cat_labels["en"]):
            if code in used_cats:
                value = cat_labels[lang].get(code) or cat_labels["en"][code]
                entries.append("[%d]=%s" % (code, lua_string(value)))
        cat_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    cat_parts.append("}\n")

    # localized profession display names
    used_profs = set(profession_vals)
    if aux is not None:
        prof_labels = aux["profession_labels"]
        prof_defs = [(None, key, prof_labels["en"][key])
                     for key in sorted(prof_labels["en"])]
    else:
        prof_defs = []
        for _, el in ET.iterparse(os.path.join(data_dir, "crafting.xml")):
            if el.tag == "profession":
                prof_defs.append((int(el.get("identifier")), el.get("key"), el.get("name")))
                el.clear()
        en_prof_lab = parse_labels(data_dir, "en", "crafting")
        prof_labels = {}
        for lang in langs:
            lab = parse_labels(data_dir, lang, "crafting")
            prof_labels[lang] = {
                key: (lab.get(ident) or en_prof_lab.get(ident) or en_name)
                for ident, key, en_name in prof_defs}
    prof_parts = ["D.PROFS = {\n"]
    for lang in langs:
        entries = []
        for _ident, key, _en_name in prof_defs:
            if key in used_profs:
                value = prof_labels[lang].get(key) or prof_labels["en"][key]
                entries.append('["%s"] = %s' % (key, lua_string(value)))
        if len(entries) != len(used_profs):
            raise AssertionError("professions used by recipes are missing from the profession table")
        prof_parts.append("%s = { %s },\n" % (lang, ", ".join(entries)))
    prof_parts.append("}\n")

    sizes["categories.lua"] = write_file(out_dir, "categories.lua", cat_parts + prof_parts)
    missing_cats = sorted(c for c in used_cats if c not in cat_labels["en"] and c != 0)
    if missing_cats:
        print("WARNING: recipe categories missing from enum: %s" % missing_cats)

    sizes["manifest.lua"] = write_file(out_dir, "manifest.lua", [
        "D.count = %d\n" % count,
        "D.base_id = %d\n" % base_id,
        "D.id_width = %d\n" % id_width,
        "D.off_width = %d\n" % off_width,
        "D.item_base = %d\n" % ITEM_BASE,
        "D.widths = { %s }\n" % ", ".join(
            "%s = %d" % (k, W[k]) for k in sorted(W)),
        "D.enums = { profession = { %s } }\n" % ", ".join(
            lua_string(v) for v in profession_vals),
        "D.langs = { %s }\n" % ", ".join(lua_string(v) for v in langs),
    ])
    print_report(baked_report, missing_en, sizes, langs, count, t0)


