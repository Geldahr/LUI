"""Bake the Bestiary search suggestion lists into the data pack.

Reads the generated Bestiary pack (manifest, records, pool and the localized
pool_<lang> files) and writes paths.lua: per language, the region > areas
and genus > subcategories lists the Tokens search suggests for `loc:` and
`gen:`, already sorted, so the client never scans or sorts the records.

The values are pool references: the client resolves them through the same
(localized) pool the records use, so a suggested name always equals the
name a record shows. Entries are deduplicated by their localized text and
sorted like the runtime list (Lua string.lower, bytewise); a child equal to
its parent is dropped ("Bree-land > Bree-land"). The English text of every
referenced name is baked too (EN_REFS / EN_NAMES): the /loc location names
are English, so French and German clients match them through it.

Instances are loc: entries of their own (no areas): their creatures have
no region in the data (4200 creatures in 169 instances), so `loc:<instance>`
is how they are found, and a /loc zone can be an instance ("Attack at
Dawn").

Usage: python tools/lore2lua/bestiary_paths.py src/Data/Bestiary
(also run at the end of convert.py --db bestiary)
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from codec import b93, emit_blob, u93, width_for  # noqa: E402

LANGS = ("en", "fr", "de")
# record scalar order (convert.py B_SCALARS / bestiary_db.lua SCALARS)
SCALARS = ["n", "bn", "tl", "v", "g", "s", "sp", "r", "a", "i", "t"]
# key -> (parent scalar, child scalar)
PATHS = {"loc": ("r", "a"), "gen": ("g", "s")}

GENERATED_HEADER = (
    "-- This Source Code Form is subject to the terms of the Mozilla Public\n"
    "-- License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    "-- file, You can obtain one at https://mozilla.org/MPL/2.0/.\n"
    "--\n"
    "-- GENERATED by LUI data tools -- DO NOT EDIT\n"
    "-- Source: LOTRO game client data\n"
)


def _read_module(path):
    """Numbers and blobs of a generated data module (blobs as bytes)."""
    with open(path, "rb") as f:
        text = f.read()
    numbers = {k.decode(): int(v) for k, v in re.findall(rb"^D\.(\w+) = (\d+)$", text, re.M)}
    blobs = {}
    for m in re.finditer(rb"^D\.(\w+) = \[(=*)\[\n", text, re.M):
        close = b"]" + m.group(2) + b"]"
        end = text.index(close, m.end())
        blobs[m.group(1).decode()] = text[m.end():end]
    return numbers, blobs


def _pool_strings(path):
    numbers, blobs = _read_module(path)
    pool, poff, w = blobs["POOL"], blobs["POFF"].decode("ascii"), numbers["poff_width"]
    count = len(poff) // w - 1
    out = [None]  # 1-based refs
    for ref in range(1, count + 1):
        start = u93(poff, (ref - 1) * w, w) - 1
        end = u93(poff, ref * w, w) - 1
        out.append(pool[start:end].decode("utf-8"))
    return out


def _lua_lower(s):
    return "".join(chr(ord(c) + 32) if "A" <= c <= "Z" else c for c in s)


def _sort_key(text):
    return (_lua_lower(text).encode("utf-8"), text.encode("utf-8"))


def emit_bestiary_paths(out_dir):
    """Write paths.lua next to the Bestiary pack; returns its size."""
    manifest, _ = _read_module(os.path.join(out_dir, "manifest.lua"))
    _, records = _read_module(os.path.join(out_dir, "records.lua"))
    count, ref_w, off_w = manifest["count"], manifest["ref_width"], manifest["off_width"]
    data, off = records["DATA"].decode("ascii"), records["OFF"].decode("ascii")

    # (parent ref, child ref or 0) pairs of every record, per key; every
    # instance is a loc parent of its own
    pairs = {key: set() for key in PATHS}
    for n in range(count):
        pos = u93(off, n * off_w, off_w) - 1
        refs = [u93(data, pos + k * ref_w, ref_w) for k in range(len(SCALARS))]
        for key, (pf, cf) in PATHS.items():
            parent = refs[SCALARS.index(pf)]
            if parent:
                pairs[key].add((parent, refs[SCALARS.index(cf)]))
        instance = refs[SCALARS.index("i")]
        if instance:
            pairs["loc"].add((instance, 0))

    parts = ["D.ref_width = %d\n" % ref_w]
    count_w = 1
    lang_blobs = []
    for lang in LANGS:
        pool_file = "pool.lua" if lang == "en" else "pool_%s.lua" % lang
        pool_path = os.path.join(out_dir, pool_file)
        if not os.path.exists(pool_path):
            continue
        pool = _pool_strings(pool_path)
        for key in PATHS:
            # by localized text: one representative ref per distinct text
            parents = {}
            for parent, child in pairs[key]:
                ptext = pool[parent]
                entry = parents.setdefault(ptext, {"ref": parent, "children": {}})
                if child:
                    ctext = pool[child]
                    if ctext != ptext:
                        entry["children"].setdefault(ctext, child)
            ordered = []
            for ptext in sorted(parents, key=_sort_key):
                entry = parents[ptext]
                children = [entry["children"][c] for c in sorted(entry["children"], key=_sort_key)]
                ordered.append((entry["ref"], children))
                count_w = max(count_w, width_for(len(children)))
            lang_blobs.append((lang, key, ordered))
    parts.append("D.count_width = %d\n" % count_w)
    # English text of every referenced name (the /loc zone names are English)
    en_pool = _pool_strings(os.path.join(out_dir, "pool.lua"))
    refs = sorted({r for key in PATHS for pair in pairs[key] for r in pair if r})
    parts.append(emit_blob("EN_REFS", "".join(b93(r, ref_w) for r in refs)))
    parts.append(emit_blob("EN_NAMES", "\n".join(en_pool[r] for r in refs)))
    for lang, key, ordered in lang_blobs:
        blob = "".join(
            b93(ref, ref_w) + b93(len(children), count_w) + "".join(b93(c, ref_w) for c in children)
            for ref, children in ordered
        )
        parts.append(emit_blob("%s_%s" % (key.upper(), lang), blob))

    path = os.path.join(out_dir, "paths.lua")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(GENERATED_HEADER)
        f.write("local D = {}\n")
        for p in parts:
            f.write(p)
        f.write("_G.LoreData = _G.LoreData or {}\n")
        f.write('_G.LoreData["Bestiary.paths"] = D\n')
        f.write("return D\n")
    for lang, key, ordered in lang_blobs:
        print("paths %s %s: %d parents, %d children" % (
            key, lang, len(ordered), sum(len(c) for _, c in ordered)))
    return os.path.getsize(path)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: bestiary_paths.py <src/Data/Bestiary>")
    print("paths.lua: %d bytes" % emit_bestiary_paths(sys.argv[1]))
